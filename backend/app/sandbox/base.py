from dataclasses import dataclass
from pathlib import Path
from typing import Protocol

OUTPUT_HEAD = 2048
OUTPUT_TAIL = 8192
TRUNCATION_MARKER = b"\n[output truncated]\n"


@dataclass(frozen=True)
class ExecResult:
    exit_code: int
    output: str
    truncated: bool


class Sandbox(Protocol):
    def start(self) -> None: ...
    def exec(self, cmd: str, timeout: float) -> ExecResult: ...
    def list_dir(self, path: str) -> ExecResult: ...
    def search(self, path: str, query: str) -> ExecResult: ...
    def read_file(self, path: str) -> str: ...
    def write_file(self, path: str, content: str) -> None: ...
    def copy_in(self, local_dir: Path) -> None: ...
    def destroy(self) -> None: ...
